export type MessageKey = keyof typeof english;
export type MessageParameters = Record<string, string | number>;
export type Translator = (key: MessageKey, parameters?: MessageParameters) => string;
export const localeFor = (language: Language) => language === 'zh' ? 'zh-CN' : 'en-US';
const singularEnglish: Partial<Record<MessageKey, string>> = {
  '{count} 个来源': '{count} source',
  '{count} 个会话': '{count} session',
  '{accuracy} · {count} 条已知记录': '{accuracy} · {count} known record',
  '{count} 条记录缺失 · 仅已知部分': '{count} missing record · known values only',
  '{metric}明细不足（{count} 个模型）': 'Incomplete {metric} values ({count} model)',
  '本范围未使用（{count} 个模型）': 'Unused in this range ({count} model)',
};
export function translate(language: Language, key: MessageKey, parameters: MessageParameters = {}): string {
  const message = language === 'en' ? (parameters.count === 1 ? singularEnglish[key] ?? english[key] : english[key]) : key;
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(parameters[name] ?? placeholder));
}

